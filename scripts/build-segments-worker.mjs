import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve, parse } from 'node:path'
// Neutral resolves the pure JS entity decoder; its browser variant requires a DOM unavailable in Workers.
const result = await build({ entryPoints: ['src/client/segments/split-worker.ts'], bundle: true, write: false, metafile: true, platform: 'neutral', mainFields: ['module', 'main'], format: 'iife', target: 'es2022', minify: true, legalComments: 'inline' })
await writeFile('src/client/segments/worker-source.ts', `// Generated by scripts/build-worker.mjs. Do not edit.\nexport const WORKER_SOURCE: string = ${JSON.stringify(result.outputFiles[0].text)}\n`)
const notices = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules')) continue
  let dir = dirname(resolve(input))
  while (dir !== parse(dir).root) {
    let pkg
    try { pkg = JSON.parse(await readFile(resolve(dir, 'package.json'), 'utf8')) } catch { dir = dirname(dir); continue }
    if (!pkg.name) { dir = dirname(dir); continue }
    if (!notices.has(pkg.name)) {
      let license
      for (const name of ['license', 'LICENSE', 'LICENSE.md', 'LICENSE-MIT', 'LICENSE.txt']) {
        try { license = await readFile(resolve(dir, name), 'utf8'); break } catch {}
      }
      if (!license && pkg.license === 'MIT' && (pkg.name === 'micromark' || pkg.name.startsWith('micromark-'))) {
        // Micromark monorepo utility tarballs omit the shared license file.
        const readme = await readFile(resolve(dir, 'readme.md'), 'utf8')
        if (!readme.includes('[MIT][license] © [Titus Wormer][author]')) throw new Error(`Unknown copyright: ${pkg.name}`)
        const mit = await readFile('LICENSE', 'utf8')
        license = 'MIT License\n\nCopyright (c) Titus Wormer\n\n' + mit.slice(mit.indexOf('Permission is hereby granted'))
      }
      if (!license) throw new Error(`Missing bundled license for ${pkg.name}`)
      notices.set(pkg.name, `${pkg.name} ${pkg.version}\n${license.trim()}`)
    }
    break
  }
}
await writeFile('SEGMENTS-THIRD-PARTY-NOTICES.txt', [...notices].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text).join('\n\n--------------------\n\n') + '\n')
