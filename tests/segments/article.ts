一个人住的第三年，我学会了一件事：再忙，也要坐下来吃饭。
以前不是这样。以前吃饭是顺便——顺手点个外卖，一边回消息一边扒完，等回过神来，碗已经空了，一天也过去了。那时候我不觉得这有什么问题，吃饭嘛，填饱肚子而已，认真吃饭听起来像句废话。
